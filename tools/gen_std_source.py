#!/usr/bin/env python3
"""Regenerate src/resolve/std_source.c from lib/std.eko. The file is
committed; this tool is never a build step.

The resolver must answer the implicit std import without a file system
dependency: a compilation root may be resolved where lib/ is absent.
The generated table carries the release file's bytes verbatim, so the
module is parsed by the ordinary lexical and syntax entry points.

One source line is one part: a joined string literal would exceed the
smallest length ISO C requires a compiler to accept, and a part per
line never does. ek_std_source_join concatenates the parts into one
arena buffer at use.

Usage: python3 tools/gen_std_source.py [output.c]
"""

import sys

SOURCE = "lib/std.eko"
OUTPUT = "src/resolve/std_source.c"


def escapes(data):
    """One C string literal body per source line, newline included."""
    lines = []
    line = ""
    for byte in data:
        ch = chr(byte)
        if ch == "\n":
            line += "\\n"
            lines.append(line)
            line = ""
        elif ch == "\t":
            line += "\\t"
        elif ch == '"':
            line += '\\"'
        elif ch == "\\":
            line += "\\\\"
        elif ch == "?":
            line += "\\?"  # never the start of a trigraph
        elif 0x20 <= byte < 0x7F:
            line += ch
        else:
            line += "\\%03o" % byte
    if line:
        lines.append(line)
    return lines


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUTPUT
    with open(SOURCE, "rb") as f:
        data = f.read()
    if b"\0" in data:
        raise SystemExit(f"{SOURCE}: a NUL byte cannot be embedded")
    body = escapes(data)
    if not body:
        body = [""]
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/gen_std_source.py from {SOURCE}. "
                "Do not edit. */\n")
        f.write('#include <string.h>\n\n')
        f.write('#include "support/arena.h"\n')
        f.write('#include "resolve/std_source.h"\n\n')
        f.write("const char *const ek_std_source_parts[] = {\n")
        for line in body:
            f.write(f'    "{line}",\n')
        f.write("};\n\n")
        f.write(f"const size_t ek_std_source_nparts = {len(body)};\n")
        f.write(f"const size_t ek_std_source_len = {len(data)};\n\n")
        f.write("char *ek_std_source_join(ek_arena *arena)\n"
                "{\n"
                "    char *buf = ek_arena_alloc(arena, "
                "ek_std_source_len + 1);\n"
                "    size_t at = 0, i;\n\n"
                "    if (!buf) {\n"
                "        return NULL;\n"
                "    }\n"
                "    for (i = 0; i < ek_std_source_nparts; i++) {\n"
                "        size_t n = strlen(ek_std_source_parts[i]);\n\n"
                "        memcpy(buf + at, ek_std_source_parts[i], n);\n"
                "        at += n;\n"
                "    }\n"
                "    buf[at] = '\\0';\n"
                "    return buf;\n"
                "}\n")
    print(f"{out}: {len(data)} bytes in {len(body)} parts from {SOURCE}")


if __name__ == "__main__":
    main()
