#!/usr/bin/env python3
"""Regenerate an embedded source table under src/resolve from one Eko
file. The files are committed; this tool is never a build step.

The resolver must answer the compiler-embedded modules without a file
system dependency: a compilation root may be resolved where the
release directories are absent. The generated table carries the file's
bytes verbatim, so the module is parsed by the ordinary lexical and
syntax entry points.

One source line is one part: a joined string literal would exceed the
smallest length ISO C requires a compiler to accept, and a part per
line never does. ek_<name>_source_join concatenates the parts into one
arena buffer at use.

Usage: python3 tools/gen_embedded_source.py <name> <source> [output.c]
"""

import sys


def escapes(data):
    """One C string literal body per source line, newline included."""
    lines = []
    line = ""
    for byte in data:
        ch = chr(byte)
        if ch == "\n":
            line += "\\n"
            lines.append(line)
            line = ""
        elif ch == "\t":
            line += "\\t"
        elif ch == '"':
            line += '\\"'
        elif ch == "\\":
            line += "\\\\"
        elif ch == "?":
            line += "\\?"  # never the start of a trigraph
        elif 0x20 <= byte < 0x7F:
            line += ch
        else:
            line += "\\%03o" % byte
    if line:
        lines.append(line)
    return lines


def main():
    if len(sys.argv) < 3:
        raise SystemExit(
            "usage: gen_embedded_source.py <name> <source> [output.c]")
    name = sys.argv[1]
    source = sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else f"src/resolve/{name}_source.c"
    with open(source, "rb") as f:
        data = f.read()
    if b"\0" in data:
        raise SystemExit(f"{source}: a NUL byte cannot be embedded")
    body = escapes(data)
    if not body:
        body = [""]
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/gen_embedded_source.py from "
                f"{source}. Do not edit. */\n")
        f.write('#include <string.h>\n\n')
        f.write('#include "support/arena.h"\n')
        f.write(f'#include "resolve/{name}_source.h"\n\n')
        f.write(f"const char *const ek_{name}_source_parts[] = {{\n")
        for line in body:
            f.write(f'    "{line}",\n')
        f.write("};\n\n")
        f.write(f"const size_t ek_{name}_source_nparts = {len(body)};\n")
        f.write(f"const size_t ek_{name}_source_len = {len(data)};\n\n")
        f.write(f"char *ek_{name}_source_join(ek_arena *arena)\n"
                "{\n"
                "    char *buf = ek_arena_alloc(arena, "
                f"ek_{name}_source_len + 1);\n"
                "    size_t at = 0, i;\n\n"
                "    if (!buf) {\n"
                "        return NULL;\n"
                "    }\n"
                f"    for (i = 0; i < ek_{name}_source_nparts; i++) {{\n"
                f"        size_t n = strlen(ek_{name}_source_parts[i]);\n\n"
                f"        memcpy(buf + at, ek_{name}_source_parts[i], n);\n"
                "        at += n;\n"
                "    }\n"
                "    buf[at] = '\\0';\n"
                "    return buf;\n"
                "}\n")
    print(f"{out}: {len(data)} bytes in {len(body)} parts from {source}")


if __name__ == "__main__":
    main()
