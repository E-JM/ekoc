#!/usr/bin/env python3
"""Regenerate src/support/xid_tables.c. The file is committed; this tool
is never a build step.

Membership is derived from the host interpreter's Unicode tables via
str.isidentifier(), which follows XID_Start / XID_Continue:

    start:    (c + 'a').isidentifier()
    continue: ('x' + c).isidentifier()

'_' is excluded from start because clause 5.5.1 adds it at the lex
layer; the tables carry the raw Unicode property, under which '_' is
XID_Continue but not XID_Start. Surrogates are skipped explicitly; they
can never appear in source text. The generated tables therefore match
the Unicode version the host Python ships (unicodedata.unidata_version;
Python 3.14 carries Unicode 16.0.0).

Usage: python3 tools/gen_xid.py [output.c]
"""

import sys
import unicodedata

MAX_CP = 0x110000
PER_LINE = 6
OUTPUT = "src/support/xid_tables.c"


def is_start(cp):
    c = chr(cp)
    return cp != 0x5F and (c + "a").isidentifier()


def is_continue(cp):
    return ("x" + chr(cp)).isidentifier()


def ranges(pred):
    out = []
    lo = None
    for cp in range(MAX_CP):
        if 0xD800 <= cp < 0xE000:
            if lo is not None:
                out.append((lo, cp - 1))
                lo = None
            continue
        if pred(cp):
            if lo is None:
                lo = cp
        elif lo is not None:
            out.append((lo, cp - 1))
            lo = None
    if lo is not None:
        out.append((lo, MAX_CP - 1))
    return out


def emit_table(name, rs):
    lines = [f"const struct ek_xid_range ek_{name}_table[] = {{"]
    for i in range(0, len(rs), PER_LINE):
        cells = " ".join(f"{{0x{lo:04X},0x{hi:04X}}}," for lo, hi in rs[i:i + PER_LINE])
        lines.append("    " + cells)
    lines.append("};")
    lines.append(f"const size_t ek_{name}_table_len = {len(rs)};")
    return lines


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUTPUT
    start = ranges(is_start)
    cont = ranges(is_continue)
    with open(out, "w") as f:
        f.write(f"/* Generated by tools/gen_xid.py; "
                f"Unicode {unicodedata.unidata_version}. Do not edit. */\n")
        f.write('#include "support/xid_tables.h"\n\n')
        for name, rs in (("xid_start", start), ("xid_continue", cont)):
            for line in emit_table(name, rs):
                f.write(line + "\n")
            f.write("\n")
    print(f"{out}: {len(start)} start ranges, {len(cont)} continue ranges "
          f"(Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
