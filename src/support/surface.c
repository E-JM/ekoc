/* The table's length, for the consult loops. */
const size_t ek_surface_rows_len
    = sizeof ek_surface_rows / sizeof ek_surface_rows[0];

/* The std generic types the compiler supplies with no declaration: a
   placeholder head carries no binders, so the count a service head
   needs is named here. */
static const struct {
    const char *name;
    size_t arity;
} supplied_generics[] = {
    {"Set", 1},
    {"Vector", 1},
};

const ek_surface_row *ek_surface_find(const char *ns, const char *member)
{
    size_t i;

    for (i = 0; i < ek_surface_rows_len; i++) {
        if (ek_surface_rows[i].name && strcmp(ek_surface_rows[i].ns, ns) == 0
            && strcmp(ek_surface_rows[i].name, member) == 0) {
            return &ek_surface_rows[i];
        }
    }
    return NULL;
}

int ek_surface_owned(const char *ns)
{
    size_t i;

    for (i = 0; i < ek_surface_rows_len; i++) {
        if (ek_surface_rows[i].name == NULL
            && strcmp(ek_surface_rows[i].ns, ns) == 0) {
            return 1;
        }
    }
    return 0;
}

size_t ek_surface_generic_arity(const char *module, const char *name)
{
    size_t i;

    if (!module || strcmp(module, "std") != 0) {
        return 0;
    }
    for (i = 0; i < sizeof supplied_generics / sizeof supplied_generics[0];
         i++) {
        if (strcmp(name, supplied_generics[i].name) == 0) {
            return supplied_generics[i].arity;
        }
    }
    return 0;
}
