#ifndef EK_RESOLVE_CAP_SOURCE_H
#define EK_RESOLVE_CAP_SOURCE_H

#include <stddef.h>

#include "support/arena.h"

/* cap/cap.eko, embedded at build time: the file's bytes as one part
   per source line, their total length, and the join that concatenates
   them. A single joined literal would exceed the smallest string
   length ISO C requires a compiler to accept, so the parts stay
   separate until use. The resolver parses the joined buffer with the
   ordinary lexical and syntax entry points, so the capability
   module's surface comes from the release file without a file system
   dependency. Generated by tools/gen_embedded_source.py;
   regeneration is a tool, never a build step. */
extern const char *const ek_cap_source_parts[];
extern const size_t ek_cap_source_nparts;
extern const size_t ek_cap_source_len;

/* The file's bytes as one NUL-terminated buffer of ek_cap_source_len
   bytes, or NULL when the arena is exhausted. The buffer belongs to
   the arena. */
char *ek_cap_source_join(ek_arena *arena);

#endif
