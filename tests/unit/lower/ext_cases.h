static const char *shim_sort =
    "static size_t cells[8];\n"
    "void *shim_cells(void)\n"
    "{\n"
    "    return cells;\n"
    "}\n"
    "void shim_fill(void *b)\n"
    "{\n"
    "    static const size_t v[5] = {30, 10, 20, 50, 0};\n"
    "    size_t i;\n"
    "    for (i = 0; i < 5; i++) {\n"
    "        ((size_t *)b)[i] = v[i];\n"
    "    }\n"
    "}\n"
    "size_t shim_at(void *b, size_t i)\n"
    "{\n"
    "    return ((size_t *)b)[i];\n"
    "}\n"
    "size_t shim_five(void)\n"
    "{\n"
    "    return 5;\n"
    "}\n"
    "size_t shim_eight(void)\n"
    "{\n"
    "    return 8;\n"
    "}\n"
    "size_t shim_n(size_t i)\n"
    "{\n"
    "    return i;\n"
    "}\n"
    "void shim_sort(void *base, size_t n, size_t size,\n"
    "               int64_t (*lt)(size_t, size_t, void *), void *ctx)\n"
    "{\n"
    "    size_t *v = base;\n"
    "    size_t i, j, key;\n"
    "    (void)size;\n"
    "    for (i = 1; i < n; i++) {\n"
    "        key = v[i];\n"
    "        j = i;\n"
    "        while (j > 0 && lt(v[j - 1], key, ctx) > 0) {\n"
    "            v[j] = v[j - 1];\n"
    "            j--;\n"
    "        }\n"
    "        v[j] = key;\n"
    "    }\n"
    "}\n";

static const char *prog_sort =
    "_cells: () -> C.Ptr.Void = extern \"shim_cells\" Pure\n"
    "_fill: (b: C.Ptr.Void) ! = extern \"shim_fill\"\n"
    "_at: (b: C.Ptr.Void, i: C.Size) -> C.Size = extern \"shim_at\" "
    "Pure\n"
    "_five: () -> C.Size = extern \"shim_five\" Pure\n"
    "_eight: () -> C.Size = extern \"shim_eight\" Pure\n"
    "_n: (i: C.Size) -> C.Size = extern \"shim_n\" Pure\n"
    "_sort: (b: C.Ptr.Void, n: C.Size, sz: C.Size,\n"
    "        lt: (C.Size, C.Size) -> Int) ! = extern \"shim_sort\"\n"
    "main: () ! =\n"
    "    b = _cells()\n"
    "    _fill(b)\n"
    "    dir = 1\n"
    "    cmp: (C.Size, C.Size) -> Int = (a, y):\n"
    "        case dir == 1:\n"
    "            True ->\n"
    "                case a < y:\n"
    "                    True -> 1\n"
    "                    False -> 0 - 1\n"
    "            False ->\n"
    "                case a < y:\n"
    "                    True -> 0 - 1\n"
    "                    False -> 1\n"
    "    _sort(b, _five(), _eight(), cmp)\n"
    "    x0 = UInt.from_u64(_at(b, _n(0)))\n"
    "    x1 = UInt.from_u64(_at(b, _n(1)))\n"
    "    x2 = UInt.from_u64(_at(b, _n(2)))\n"
    "    w = 0\n"
    "    if x0 > x1:\n"
    "        if x1 > x2:\n"
    "            w := 1\n"
    "            _\n"
    "    d = 1 / w\n"
    "    _ := d\n"
    "    _\n";

#endif
